def _builtin_to_simplified(text: str) -> str:
    """使用内置映射表进行繁简转换（适用于港股公司名高频场景）。"""
    if not text:
        return text
    result = []
    for char in text:
        if char in BUILTIN_TRADITIONAL_TO_SIMPLIFIED:
            result.append(BUILTIN_TRADITIONAL_TO_SIMPLIFIED[char])
        else:
            result.append(char)
    return "".join(result)


def to_simplified(text: str, prefer_builtin: bool = False) -> str:
    """
    将繁体中文文本转换为简体（优先用于港股公司名统一）。

    Args:
        text: 输入文本（可能包含繁体字）
        prefer_builtin: 是否优先使用内置映射表（默认False，优先使用opencc/zhconv）

    Returns:
        简体中文文本

    Examples:
        >>> to_simplified("上海新榜信息技術股份有限公司")
        '上海新榜信息技术股份有限公司'
        >>> to_simplified("騰訊控股有限公司")
        '腾讯控股有限公司'
    """
    if not text:
        return text

    # 清理空白和异常字符
    cleaned = str(text).strip()
    if not cleaned:
        return cleaned

    # 优先使用内置映射表（针对港股公司名高频字优化）
    if prefer_builtin or not (_HAS_OPENCC or _HAS_ZHCONV):
        return _builtin_to_simplified(cleaned)

    # 使用opencc（最准确）
    if _HAS_OPENCC and _OPENCC_CONVERTER:
        try:
            return _OPENCC_CONVERTER.convert(cleaned)
        except Exception:
            return _builtin_to_simplified(cleaned)

    # 使用zhconv（轻量级）
    if _HAS_ZHCONV:
        try:
            return zhconv.convert(cleaned, "zh-cn")
        except Exception:
            return _builtin_to_simplified(cleaned)

    # 兜底：内置映射表
    return _builtin_to_simplified(cleaned)


def normalize_company_name(name: str) -> str:
    """
    规范化港股公司名称（去除多余空白、统一为简体）。

    Args:
        name: 公司名称（可能包含繁体字、多余空白、全角字符）

    Returns:
        规范化后的简体公司名称
    """
    if not name:
        return name

    # 1. 清理空白
    cleaned = str(name).strip()
    cleaned = re.sub(r"\s+", "", cleaned)  # 去除所有空白字符

    # 2. 全角字符转半角（数字、字母）
    def _fullwidth_to_halfwidth(char: str) -> str:
        code = ord(char)
        # 全角数字和字母范围：FF00-FFEF
        if 0xFF01 <= code <= 0xFF5E:
            return chr(code - 0xFEE0)
        # 全角空格
        if code == 0x3000:
            return " "
        return char

    cleaned = "".join(_fullwidth_to_halfwidth(c) for c in cleaned)

    # 3. 繁体转简体（优先内置映射表，针对港股公司名优化）
    simplified = to_simplified(cleaned, prefer_builtin=True)

    # 4. 再次清理空白（转换后可能有新空白）
    simplified = re.sub(r"\s+", "", simplified)

    return simplified


